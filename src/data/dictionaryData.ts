// High speed search helper with fuzzy/accent normalization
function normalizeSearch(str: string): string {
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove diacritics
    .replace(/[‘'ʻ’`]/g, '') // normalize Uzbek apostrophes (o‘ -> o)
    .replace(/ä/g, 'ae')
    .replace(/ö/g, 'oe')
    .replace(/ü/g, 'ue')
    .replace(/ß/g, 'ss');
}

export function searchDictionary(
  query: string,
  sourceLang: string = 'all',
  cefr: string = 'all',
  pos: string = 'all',
  category: string = 'all',
  gender: string = 'all',
  limit: number = 200
): DictionaryEntry[] {
  const cleanQ = query.trim();
  const normQ = normalizeSearch(cleanQ);

  if (!cleanQ && cefr === 'all' && pos === 'all' && category === 'all' && gender === 'all') {
    return FULL_DICTIONARY.slice(0, limit);
  }

  return FULL_DICTIONARY.filter(item => {
    // 1. Filter conditions
    if (cefr !== 'all' && item.cefr !== cefr) return false;
    if (pos !== 'all' && item.pos !== pos) return false;
    if (category !== 'all' && item.category !== category) return false;
    if (gender !== 'all' && item.deGender !== gender) return false;

    if (!cleanQ) return true;

    // 2. Language-specific matching
    const normEn = normalizeSearch(item.en);
    const normUz = normalizeSearch(item.uz);
    const normDe = normalizeSearch(item.de);

    if (sourceLang === 'en') {
      return normEn.includes(normQ);
    }
    if (sourceLang === 'uz') {
      return normUz.includes(normQ);
    }
    if (sourceLang === 'de') {
      return normDe.includes(normQ);
    }

    // Default 'all': search across English, Uzbek, German, notes, and category
    return (
      normEn.includes(normQ) ||
      normUz.includes(normQ) ||
      normDe.includes(normQ) ||
      (item.category && normalizeSearch(item.category).includes(normQ)) ||
      (item.notes && normalizeSearch(item.notes).includes(normQ))
    );
  }).slice(0, limit);
}
